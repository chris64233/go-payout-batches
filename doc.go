// Package gopayoutbatches 实现商户应付款的批次冻结与银行结果确认。
//
// 核心能力：
//   - 应付款明细登记（精确金额，仅可结算状态可入批次）；
//   - 批次创建：金额快照 + 原子冻结，任一明细不满足条件则整批回滚，
//     同一明细不能同时出现在两个未结束批次中；
//   - 批次提交银行：外部提交号幂等（同号同内容返回首次结果，同号换内容报冲突），
//     提交与取消互斥，已提交批次不可本地取消；
//   - 银行回执确认：按批次 + 提交版本匹配，兼容重复/乱序/迟到回执；
//     失败在同一持久化事务内释放全部明细，成功生成唯一结算记录与通知，旧回执不覆盖终态。
//
// 入口类型为 PayoutService，存储为 Store（内存事务实现）。
